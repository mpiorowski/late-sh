#[derive(Clone, Debug, Default)]
pub struct DailyCompletionStatus {
    pub completed_games: HashSet<DailyPuzzle>,
    pub completed_difficulties: HashSet<(DailyPuzzle, String)>,
}

impl DailyCompletionStatus {
    pub fn completed(&self, game: DailyPuzzle) -> bool {
        self.completed_games.contains(&game)
    }

    pub fn completed_difficulty(&self, game: DailyPuzzle, difficulty_key: &str) -> bool {
        self.completed_difficulties
            .contains(&(game, difficulty_key.to_string()))
    }

    pub fn mark_completed(&mut self, game: DailyPuzzle, difficulty_key: String) {
        self.completed_games.insert(game);
        self.completed_difficulties.insert((game, difficulty_key));
    }
}

