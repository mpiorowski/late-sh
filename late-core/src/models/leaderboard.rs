/// UTC calendar-month window over a `puzzle_date` date column.
const MONTH_DATE_FILTER: &str = "date_trunc('month', now() AT TIME ZONE 'UTC')::date";
/// UTC calendar-month window over a timestamptz column.
const MONTH_TS_FILTER: &str = "date_trunc('month', now() AT TIME ZONE 'UTC') AT TIME ZONE 'UTC'";
/// Rows kept per board. Deep enough that the page can show an around-you
/// tail for almost everyone; RANK ties can push slightly past it.
const BOARD_DEPTH: i64 = 500;

#[derive(Clone)]
pub struct LeaderboardEntry {
    pub username: String,
    pub user_id: Uuid,
    pub count: u32,
}

#[derive(Clone)]
pub struct RankedEntry {
    pub username: String,
    pub user_id: Uuid,
    pub rank: i64,
    pub value: i64,
    /// Optional flavor after the username (the Lateania boards put the
    /// character's class here). Pure decoration: the page drops it before the
    /// rank, name, or value when width runs short.
    pub note: Option<String>,
}

/// Defines a roster enum plus its `ALL` list from one variant list, the same
/// guarantee as `chip_moves!`: a variant cannot exist without an `ALL` entry,
/// so SQL generated by iterating `ALL` can never silently skip a game.
macro_rules! roster {
    ($(#[$doc:meta])* $name:ident: $($variant:ident),+ $(,)?) => {
        $(#[$doc])*
        #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
        pub enum $name {
            $($variant,)+
        }

        impl $name {
            /// Every variant in declaration order, generated from the same
            /// list as the enum itself. Board and page ordering follow it.
            pub const ALL: &'static [Self] = &[$(Self::$variant),+];
        }
    };
}

roster!(
    /// The daily-puzzle roster. Each variant is one `<game>_daily_wins` fact
    /// table. Everything derived from a daily win, the per-game win-count
    /// boards, Arcade Wins points, today's champions, and the per-user daily
    /// completion statuses, is generated by iterating `ALL`, so adding a
    /// daily game here enrolls it in all four surfaces at once. The one thing
    /// the roster cannot enforce: the new game's win-insert statement must
    /// compose `bump_daily_win_total_sql`, or its all-time board stays empty.
    DailyPuzzle: Sudoku, Nonogram, Minesweeper, Solitaire, LeWord, RubiksCube, SlidingPuzzle
);

roster!(
    /// The score-game roster. Each variant has final-score events in
    /// `game_score_events` plus a legacy best-score table; monthly boards
    /// union both, all-time boards read the legacy table of record.
    ScoreGame: Lateris, TwentyFortyEight, Snake, Traffic
);

roster!(
    /// The external roguelike-door roster: games whose runs are ingested
    /// from their host's log files into `door_runs`
    /// (devdocs/PLAN-ROGUELIKE-BOARDS.md). Each variant gets the uniform
    /// board triple: Wins (all-time), Deepest dive, and Top score (monthly +
    /// all-time), all from the per-window union query.
    DoorGame: Dcss, Nethack, Brogue
);

impl DailyPuzzle {
    /// The stable game key used in activity params and status rows.
    pub const fn key(self) -> &'static str {
        match self {
            Self::Sudoku => "sudoku",
            Self::Nonogram => "nonogram",
            Self::Minesweeper => "minesweeper",
            Self::Solitaire => "solitaire",
            Self::LeWord => "le_word",
            Self::RubiksCube => "rubiks_cube",
            Self::SlidingPuzzle => "sliding_puzzle",
        }
    }

    pub const fn title(self) -> &'static str {
        match self {
            Self::Sudoku => "Sudoku",
            Self::Nonogram => "Nonograms",
            Self::Minesweeper => "Minesweeper",
            Self::Solitaire => "Solitaire",
            Self::LeWord => "Le Word",
            Self::RubiksCube => "Rubik's Cube",
            Self::SlidingPuzzle => "Sliding Puzzle",
        }
    }

    /// The per-user daily-win fact table.
    const fn wins_table(self) -> &'static str {
        match self {
            Self::Sudoku => "sudoku_daily_wins",
            Self::Nonogram => "nonogram_daily_wins",
            Self::Minesweeper => "minesweeper_daily_wins",
            Self::Solitaire => "solitaire_daily_wins",
            Self::LeWord => "le_word_daily_wins",
            Self::RubiksCube => "rubiks_cube_daily_wins",
            Self::SlidingPuzzle => "sliding_puzzle_daily_wins",
        }
    }

    /// SQL expression producing this puzzle's Arcade Wins points for one win
    /// row. Every weight comes from [`Difficulty::points`]; a difficulty key
    /// outside the puzzle's real set scores 0, never a silent default.
    fn points_sql(self) -> String {
        match self {
            Self::Sudoku | Self::Nonogram | Self::Minesweeper | Self::SlidingPuzzle => {
                let whens: String = Difficulty::ALL
                    .iter()
                    .map(|d| format!("WHEN '{}' THEN {}", d.key(), d.points()))
                    .collect::<Vec<_>>()
                    .join(" ");
                format!("CASE difficulty_key {whens} ELSE 0 END")
            }
            Self::Solitaire => format!(
                "CASE difficulty_key WHEN 'draw-1' THEN {} WHEN 'draw-3' THEN {} ELSE 0 END",
                Difficulty::Easy.points(),
                Difficulty::Hard.points()
            ),
            Self::LeWord => Difficulty::Easy.points().to_string(),
            Self::RubiksCube => Difficulty::Medium.points().to_string(),
        }
    }

    /// SQL expression for the difficulty column of a daily-status row.
    /// Fixed-tier puzzles have no difficulty column and report `'daily'`.
    const fn status_difficulty_sql(self) -> &'static str {
        match self {
            Self::Sudoku
            | Self::Nonogram
            | Self::Minesweeper
            | Self::Solitaire
            | Self::SlidingPuzzle => "difficulty_key",
            Self::LeWord | Self::RubiksCube => "'daily'",
        }
    }

    pub fn from_key(key: &str) -> Option<Self> {
        Self::ALL.iter().copied().find(|game| game.key() == key)
    }
}

