/// Abilities a character of this class has unlocked at this level, lowest level first.
pub fn unlocked_for(class: Class, level: i32) -> Vec<&'static Ability> {
    let mut out: Vec<&'static Ability> = ABILITIES
        .iter()
        .filter(|a| a.class == class && a.level_req <= level)
        .collect();
    out.sort_by_key(|a| a.level_req);
    out
}

/// The ability a class learns exactly at `level`, if any (for level-up messages).
pub fn learned_at(class: Class, level: i32) -> Option<&'static Ability> {
    ABILITIES
        .iter()
        .find(|a| a.class == class && a.level_req == level)
}
